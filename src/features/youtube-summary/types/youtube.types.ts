/**
 * YouTube Video Summarisation Types
 * Sahayak Browser Extension (Manifest V3)
 */

export interface YouTubeVideoMetadata {
  videoId: string;
  title: string;
  channelName: string;
  videoUrl: string;
  thumbnailUrl: string;
  durationSeconds?: number;
  durationFormatted?: string;
  isShort?: boolean;
}

export interface TranscriptSegment {
  startSeconds: number;
  durationSeconds: number;
  timestamp: string; // e.g. "01:23" or "1:02:15"
  text: string;
}

export interface TranscriptTrack {
  languageCode: string;
  languageName: string;
  isAutoGenerated: boolean;
  baseUrl: string;
}

export type TranscriptErrorCode =
  | 'NO_CAPTIONS'
  | 'UNPLAYABLE'
  | 'RESTRICTED'
  | 'NETWORK_ERROR'
  | 'EXTRACTION_FAILED'
  | 'INVALID_URL';

export interface TranscriptResult {
  success: boolean;
  segments?: TranscriptSegment[];
  rawText?: string;
  language?: string;
  isAutoGenerated?: boolean;
  error?: TranscriptErrorCode;
  errorMessage?: string;
}

export interface ImportantMoment {
  timestamp: string; // e.g. "02:45"
  seconds: number;
  title: string;
  description: string;
}

export interface YouTubeStructuredSummary {
  overview: string;
  keyTakeaways: string[];
  detailedSummary: string;
  importantMoments: ImportantMoment[];
  importantFacts: string[];
  conclusion: string;
  topicsAndKeywords: string[];
}

export type YouTubeSummaryStatus =
  | 'idle'
  | 'detecting'
  | 'extracting_metadata'
  | 'extracting_transcript'
  | 'summarizing'
  | 'success'
  | 'error';

export interface YouTubeSummaryState {
  status: YouTubeSummaryStatus;
  metadata: YouTubeVideoMetadata | null;
  transcriptSegments: TranscriptSegment[] | null;
  summary: YouTubeStructuredSummary | null;
  error: string | null;
  isYouTubePage: boolean;
}
