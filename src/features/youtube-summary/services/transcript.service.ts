/**
 * YouTube Transcript Retrieval Service
 * Retrieves and parses official captions from YouTube timedtext tracks without bypassing restrictions.
 */

import { TranscriptResult, TranscriptTrack } from '../types/youtube.types';
import { parseYouTubeUrl } from './youtube-detector.service';
import { cleanAndMergeTranscript } from './transcript-cleaner.service';

/**
 * Parses YouTube timedtext XML format:
 * <transcript><text start="1.5" dur="2.4">Segment text</text></transcript>
 */
export function parseTimedTextXml(
  xmlString: string
): Array<{ start: number; dur: number; text: string }> {
  if (!xmlString || typeof xmlString !== 'string') return [];

  const segments: Array<{ start: number; dur: number; text: string }> = [];

  // Match <text start="..." dur="...">text</text>
  const regex = /<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/gi;
  let match: RegExpExecArray | null;

  while ((match = regex.exec(xmlString)) !== null) {
    const start = parseFloat(match[1]) || 0;
    const dur = match[2] ? parseFloat(match[2]) : 2.0;
    const rawText = match[3] || '';
    if (rawText.trim()) {
      segments.push({ start, dur, text: rawText });
    }
  }

  return segments;
}

/**
 * Parses YouTube timedtext JSON3 format:
 * { events: [ { tStartMs: 1500, dDurationMs: 2400, segs: [{ utf8: "text" }] } ] }
 */
export function parseTimedTextJson3(
  jsonObj: unknown
): Array<{ start: number; dur: number; text: string }> {
  if (!jsonObj || typeof jsonObj !== 'object') return [];

  const obj = jsonObj as {
    events?: Array<{ tStartMs?: number; dDurationMs?: number; segs?: Array<{ utf8?: string }> }>;
  };
  if (!Array.isArray(obj.events)) return [];

  const segments: Array<{ start: number; dur: number; text: string }> = [];

  for (const event of obj.events) {
    if (!event.segs || !Array.isArray(event.segs)) continue;

    const text = event.segs
      .map((s) => s.utf8 || '')
      .join('')
      .trim();

    if (!text) continue;

    const start = (event.tStartMs || 0) / 1000;
    const dur = (event.dDurationMs || 0) / 1000;

    segments.push({ start, dur, text });
  }

  return segments;
}

/**
 * Selects the optimal caption track from available tracks.
 * Prefers manual English tracks, falls back to ASR (auto-generated) English, then first available track.
 */
export function selectBestCaptionTrack(
  tracks: TranscriptTrack[],
  preferredLang: string = 'en'
): TranscriptTrack | null {
  if (!tracks || tracks.length === 0) return null;

  // 1. Manual track in preferred language
  const manualPreferred = tracks.find(
    (t) => t.languageCode.startsWith(preferredLang) && !t.isAutoGenerated
  );
  if (manualPreferred) return manualPreferred;

  // 2. Auto-generated track in preferred language
  const autoPreferred = tracks.find(
    (t) => t.languageCode.startsWith(preferredLang) && t.isAutoGenerated
  );
  if (autoPreferred) return autoPreferred;

  // 3. Any manual track
  const anyManual = tracks.find((t) => !t.isAutoGenerated);
  if (anyManual) return anyManual;

  // 4. Default to first track
  return tracks[0];
}

/**
 * Extracts player response JSON from YouTube watch page HTML.
 */
export function extractPlayerResponseFromHtml(html: string): {
  playabilityStatus?: { status?: string; reason?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: Array<{
        baseUrl: string;
        name?: { simpleText?: string; runs?: Array<{ text: string }> };
        vssId?: string;
        languageCode: string;
        kind?: string;
      }>;
    };
  };
} | null {
  if (!html) return null;

  // Pattern: ytInitialPlayerResponse = {...};
  const regex = /ytInitialPlayerResponse\s*=\s*({.+?});(?:var\s|const\s|<\/script>)/;
  const match = html.match(regex);
  if (match && match[1]) {
    try {
      return JSON.parse(match[1]);
    } catch {
      // In case regex caught trailing content, try progressive JSON parse
    }
  }

  // Fallback: window["ytInitialPlayerResponse"] = {...}
  const regex2 = /var\s+ytInitialPlayerResponse\s*=\s*({[\s\S]+?});\s*(?:var\s+meta|<\/script>)/;
  const match2 = html.match(regex2);
  if (match2 && match2[1]) {
    try {
      return JSON.parse(match2[1]);
    } catch {
      // Ignore
    }
  }

  return null;
}

/**
 * Fetches and parses caption track text from YouTube timedtext baseUrl.
 */
export async function fetchTranscriptFromBaseUrl(
  baseUrl: string
): Promise<Array<{ start: number; dur: number; text: string }>> {
  // Try fetching as JSON3 first
  try {
    const jsonUrl = baseUrl.includes('fmt=') ? baseUrl : `${baseUrl}&fmt=json3`;
    const res = await fetch(jsonUrl);
    if (res.ok) {
      const text = await res.text();
      try {
        const json = JSON.parse(text);
        const parsed = parseTimedTextJson3(json);
        if (parsed.length > 0) return parsed;
      } catch {
        // If it's XML despite fmt=json3
        const parsedXml = parseTimedTextXml(text);
        if (parsedXml.length > 0) return parsedXml;
      }
    }
  } catch {
    // Fall back to direct XML fetch
  }

  // Direct fetch fallback
  const directRes = await fetch(baseUrl);
  if (!directRes.ok) {
    throw new Error(`Timedtext HTTP error: ${directRes.status}`);
  }
  const xmlContent = await directRes.text();
  return parseTimedTextXml(xmlContent);
}

/**
 * Retrieves YouTube video captions for a video ID or URL.
 * Complies with YouTube terms and does not attempt to bypass paywalls or private settings.
 */
export async function retrieveYouTubeTranscript(
  urlOrId: string,
  preferredLang: string = 'en',
  injectedCaptionTracks?: TranscriptTrack[]
): Promise<TranscriptResult> {
  const parsed = parseYouTubeUrl(
    urlOrId.includes('://') ? urlOrId : `https://www.youtube.com/watch?v=${urlOrId}`
  );
  if (!parsed.isValid || !parsed.videoId) {
    return {
      success: false,
      error: 'INVALID_URL',
      errorMessage: 'The provided URL or ID is not a valid YouTube video.',
    };
  }

  const videoId = parsed.videoId;

  // 1. If caption tracks were passed directly from content script
  let availableTracks: TranscriptTrack[] = injectedCaptionTracks || [];

  // 2. If no tracks injected, fetch the watch page HTML to inspect ytInitialPlayerResponse
  if (availableTracks.length === 0) {
    try {
      const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;
      const res = await fetch(watchUrl, {
        headers: {
          'Accept-Language': `${preferredLang},en;q=0.9`,
        },
      });

      if (!res.ok) {
        return {
          success: false,
          error: 'NETWORK_ERROR',
          errorMessage: `Failed to load YouTube video page (HTTP ${res.status}).`,
        };
      }

      const html = await res.text();
      const playerResponse = extractPlayerResponseFromHtml(html);

      if (playerResponse?.playabilityStatus) {
        const status = playerResponse.playabilityStatus.status;
        if (status === 'UNPLAYABLE') {
          return {
            success: false,
            error: 'UNPLAYABLE',
            errorMessage:
              playerResponse.playabilityStatus.reason || 'This video is unplayable or unavailable.',
          };
        }
        if (status === 'LOGIN_REQUIRED') {
          return {
            success: false,
            error: 'RESTRICTED',
            errorMessage:
              playerResponse.playabilityStatus.reason ||
              'This video requires login (age-restricted, private, or members-only).',
          };
        }
      }

      const rawTracks =
        playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];

      availableTracks = rawTracks.map((t) => {
        const name =
          t.name?.simpleText ||
          (t.name?.runs ? t.name.runs.map((r) => r.text).join('') : t.languageCode);
        return {
          languageCode: t.languageCode,
          languageName: name,
          isAutoGenerated: t.kind === 'asr',
          baseUrl: t.baseUrl,
        };
      });
    } catch (err) {
      return {
        success: false,
        error: 'NETWORK_ERROR',
        errorMessage:
          err instanceof Error ? err.message : 'Network error loading video transcript.',
      };
    }
  }

  if (availableTracks.length === 0) {
    return {
      success: false,
      error: 'NO_CAPTIONS',
      errorMessage:
        'No captions or transcripts are available for this video. The creator may have disabled subtitles, or automatic captions have not yet finished processing.',
    };
  }

  const selectedTrack = selectBestCaptionTrack(availableTracks, preferredLang);
  if (!selectedTrack || !selectedTrack.baseUrl) {
    return {
      success: false,
      error: 'NO_CAPTIONS',
      errorMessage: 'Could not resolve an accessible caption track for this video.',
    };
  }

  try {
    const rawSegments = await fetchTranscriptFromBaseUrl(selectedTrack.baseUrl);
    if (!rawSegments || rawSegments.length === 0) {
      return {
        success: false,
        error: 'NO_CAPTIONS',
        errorMessage: 'The caption track returned no readable text segments.',
      };
    }

    const cleanedSegments = cleanAndMergeTranscript(rawSegments);

    return {
      success: true,
      segments: cleanedSegments,
      language: selectedTrack.languageName,
      isAutoGenerated: selectedTrack.isAutoGenerated,
    };
  } catch (err) {
    return {
      success: false,
      error: 'EXTRACTION_FAILED',
      errorMessage:
        err instanceof Error ? err.message : 'Failed to retrieve transcript text from YouTube.',
    };
  }
}
